#!/usr/bin/env bash
# Rebuilds docs/CN-VPN-QUEUE.md: resources that need a mainland-China connection.
# Sources: archive entries fetched only via relay or failed (.cn hosts), plus data/cn_vpn_needed.txt.
cd "$(dirname "$0")/.."
{
echo "# Resources that need a China VPN"
echo
echo "Generated by tools/vpn_queue.sh on $(date -u +%F). Once the VPN is active, fetch these directly and replace the relay copies; tools/archive_sources.sh keeps the SHA-256."
echo
echo "## A. Already archived via relay or failed: re-fetch the original directly"
echo
echo "| URL | Current state | Copy |"
echo "|---|---|---|"
awk -F'\t' '($4=="relay" || $5!="200") && ($2 ~ /\.cn\// || $2 ~ /\.cn$/ || $2 ~ /gitee|atomgit|openatom|kaiyuanshe|10100\.com/) {printf "| %s | %s %s | sources/archive/%s |\n",$2,$4,$5,$3}' sources/archive/index.tsv | sort -u
echo
echo "## B. Not obtainable without a VPN: find, fetch and analyse"
echo
echo "| URL | Why it matters | What to extract |"
echo "|---|---|---|"
[ -f data/cn_vpn_needed.txt ] && awk -F'\t' 'NF>=1{printf "| %s | %s | %s |\n",$1,$2,$3}' data/cn_vpn_needed.txt | sort -u
echo
echo "## C. Planned searches (from inside China)"
echo
echo "- Full text and signatories of the Shanghai Open Source Innovation International Cooperation Declaration (Sept 2026)"
echo "- National register of social organisations (chinanpo.mca.gov.cn): OpenAtom, Chance Foundation (credit code, establishment date, governing body)"
echo "- Disbursements and beneficiaries of the Hangzhou, Guangdong, Shenzhen and Jiangsu Zijin funds (public award lists 公示)"
echo "- Public-administration reuse cases on provincial portals (政务, 信创, government open-source code repositories)"
echo "- Baidu/WeChat searches for 数字公地 (digital commons) and 中欧开源 (EU–China open source), not indexed outside China"
echo
echo "## D. Local copy of every Chinese source (run with VPN active)"
echo
N=$(grep -rhoE "https?://[^ )\"<>|]+" data docs reviews 2>/dev/null | grep -E "\.cn(/|$)|gitee\.com|atomgit\.com|openatom\.org|kaiyuanshe|mp\.weixin\.qq\.com|gitcode|csdn\.net|oschina" | sort -u | wc -l)
echo "Run tools/vpn_fetch.sh with the VPN active: it copies every URL in B plus all $N distinct Chinese URLs cited in data/, docs/ and reviews/ (gov.cn, Gitee, AtomGit, OpenAtom, WeChat, CSDN), with linked attachments (公示表, PDF, XLS), into sources/archive-vpn/ with SHA-256 in index.tsv. Then commit sources/archive-vpn/."
} > docs/CN-VPN-QUEUE.md
