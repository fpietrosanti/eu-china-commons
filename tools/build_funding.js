#!/usr/bin/env node
// Builds docs/FUNDING-COMPARISON.md and site/data/funding.json from data/funding/{eu,cn}.json.
// Conversion: ECB annual average rate of the record's year (data/funding/fx_ecb_cny.json).
const fs = require('fs');
const path = require('path');
const root = path.join(__dirname, '..');
const rd = (p, d) => { try { return JSON.parse(fs.readFileSync(path.join(root, p), 'utf8')); } catch { return d; } };

const fx = rd('data/funding/fx_ecb_cny.json', { rates: {} });
const recs = [...rd('data/funding/eu.json', []), ...rd('data/funding/cn.json', [])];
const coverage = rd('data/funding/coverage.json', []);

const REPO = 'https://github.com/fpietrosanti/eu-china-commons';
const ISSUES = `${REPO}/issues/new?labels=funding-data&title=Funding%20data%3A%20`;
const EMAIL = 'TODO-public-email@eu-china-commons.eu'; // TODO: replace when the public mailbox exists

const lastRate = () => { const y = Object.keys(fx.rates).sort().pop(); return fx.rates[y]; };
function toEur(r) {
  if (r.currency === 'EUR') return { eur: r.amount, rate: 1 };
  if (r.currency === 'CNY') {
    const rate = fx.rates[r.year] || lastRate();
    return { eur: r.amount / rate, rate, approxRate: !fx.rates[r.year] };
  }
  return { eur: null, rate: null };
}
const years = (p) => { const m = /^(\d{4})\D+(\d{4})$/.exec(p || ''); return m ? +m[2] - +m[1] + 1 : 1; };
const fmt = (n) => n == null ? 'n/a' : (n >= 1e6 ? (n / 1e6).toFixed(1) + ' M' : n >= 1e3 ? (n / 1e3).toFixed(0) + ' k' : n.toFixed(0));
const fmtOrig = (r) => `${fmt(r.amount)} ${r.currency}`;

const rows = recs.map((r) => {
  const c = toEur(r);
  const annualEur = c.eur == null ? null : (r.period ? c.eur / years(r.period) : c.eur);
  return { ...r, eur: c.eur, rate: c.rate, approxRate: c.approxRate, annualEur };
});

const NOTICE = [
  '> **Open-source research, not official statistics.** These figures are collected from publicly available sources (budgets, programme pages, official filings, press) by the Europe–China Digital Commons Observatory. They are incomplete, may contain errors, and compare instruments that are not always equivalent. Absence of a jurisdiction means *we found nothing*, not that it spends nothing.',
  '>',
  `> **Help us improve them:** open an issue on GitHub (${ISSUES}) or write to ${EMAIL}. Please include the source (link, document, page) for any correction or addition.`,
].join('\n');

let md = `# Funding for open source — EU vs China (public money and private corporate money)\n\n*Generated by tools/build_funding.js on ${new Date().toISOString().slice(0, 10)}. Do not edit by hand.*\n\n${NOTICE}\n\n`;
md += `## Method\n- Amounts kept in the original currency and converted to EUR at the **ECB annual average rate** of the record's year (${fx.source || 'ECB'}). Rates used: ${Object.entries(fx.rates).filter(([y]) => +y >= 2020).map(([y, v]) => `${y}: ${v}`).join(', ')} CNY/EUR.\n- **Totals include only \`summable\` records**: disbursed or budgeted, annual, open-source-specific. Multi-year envelopes are shown separately and annualised for reference only. Per-project caps are never summed.\n- Evidence levels A–D as in docs/METHODOLOGY.md §4. Fact = disbursed/budgeted with a source; commitment = envelope or announcement.\n\n`;

// 1. Summable totals by year and side, public and private money kept apart
const isPrivate = (r) => /^private-/.test(r.level) || r.instrument_type === 'donation' || r.instrument_type === 'membership-fees' || r.instrument_type === 'sponsorship';
function totalsTable(title, pick, note) {
  const sum = {};
  for (const r of rows.filter((r) => r.summable && r.eur != null && pick(r))) {
    const k = `${r.year}|${r.side}`;
    sum[k] = (sum[k] || 0) + r.eur;
  }
  const ys = [...new Set(rows.filter((r) => r.summable && pick(r)).map((r) => r.year))].sort();
  let t = `## ${title}\n\n| Year | EU | China | CN/EU |\n|---|---|---|---|\n`;
  for (const y of ys) {
    const e = sum[`${y}|EU`] || 0, c = sum[`${y}|CN`] || 0;
    t += `| ${y} | ${e ? fmt(e) : 'not documented'} | ${c ? fmt(c) : 'not documented'} | ${e && c ? (c / e).toFixed(2) : 'n/a'} |\n`;
  }
  return t + `\n${note}\n\n`;
}
md += totalsTable('1. Public money: annual totals (summable records only, EUR)', (r) => !isPrivate(r),
  '*Inference warning: the totals reflect what is documented, which is much more for the EU (published budgets) than for China (caps and envelopes dominate).*');
md += totalsTable('1a. Private corporate money via foundations and company programmes (summable records only, EUR)', isPrivate,
  '*Never added to public money. China: OpenAtom filed donation income; EU: European foundations\' corporate income (membership, donations, sponsorship). Donor nationality matters: see the records\' notes.*');

// 1b. By instrument type: how money reaches beneficiaries (grants, adoption subsidies, tax credits…)
const it = {};
for (const r of rows) {
  const k = `${r.instrument_type || 'unclassified'}|${r.side}`;
  (it[k] = it[k] || { t: r.instrument_type || 'unclassified', side: r.side, n: 0, eur: 0 });
  it[k].n++;
  if (r.summable && r.eur != null) it[k].eur += r.eur;
}
const types = [...new Set(Object.values(it).map((v) => v.t))].sort();
md += `## 1b. By instrument type\n\n| Instrument | EU records | EU summable (EUR) | CN records | CN summable (EUR) |\n|---|---|---|---|---|\n`;
for (const t of types) {
  const e = it[`${t}|EU`] || { n: 0, eur: 0 }, c = it[`${t}|CN`] || { n: 0, eur: 0 };
  md += `| ${t} | ${e.n} | ${fmt(e.eur)} | ${c.n} | ${fmt(c.eur)} |\n`;
}
md += `\nGrants (*fondo perduto*), adoption subsidies and tax credits for firms adopting strategic national open-source technologies are in scope; when only a rate or a cap is published they are listed but not summed.\n\n`;

// 1c. Per-project caps: China funds mostly through ceilings, so compare the ceilings themselves
const caps = rows.filter((r) => r.amount_type === 'cap-per-project' && r.eur != null).sort((a, b) => b.eur - a.eur);
if (caps.length) {
  md += `## 1c. Largest per-project caps (not summable)\n\n| Jurisdiction | Instrument | Year | Cap (original) | Cap (EUR) | Ev. |\n|---|---|---|---|---|---|\n`;
  for (const r of caps.slice(0, 15)) md += `| ${r.jurisdiction}${r.province ? ` (${r.province})` : ''} | ${r.instrument} | ${r.year} | ${fmtOrig(r)} | ${fmt(r.eur)} | ${r.evidence} |\n`;
  md += `\n*A cap is a ceiling per project, not money spent; actual awards are in award notices (拟资助名单), not yet collected.*\n\n`;
}

// 2. By jurisdiction
const by = {};
for (const r of rows) {
  const k = `${r.side}|${r.level}|${r.jurisdiction}`;
  (by[k] = by[k] || { side: r.side, level: r.level, j: r.jurisdiction, ann: 0, env: 0, caps: 0, n: 0 });
  by[k].n++;
  if (r.summable && r.eur != null) by[k].ann += r.eur;
  else if (r.amount_type === 'committed-envelope' && r.annualEur != null) by[k].env += r.annualEur;
  else if (r.amount_type === 'cap-per-project') by[k].caps++;
}
const order = ['eu-institution', 'member-state', 'cn-central', 'cn-province', 'cn-city'];
md += `## 2. By jurisdiction\n\n| Side | Level | Jurisdiction | Summable, all years (EUR) | Envelopes, annualised (EUR/yr) | Per-project caps (count) | Records |\n|---|---|---|---|---|---|---|\n`;
for (const v of Object.values(by).sort((a, b) => order.indexOf(a.level) - order.indexOf(b.level) || b.ann - a.ann)) {
  md += `| ${v.side} | ${v.level} | ${v.j} | ${fmt(v.ann)} | ${v.env ? fmt(v.env) : '–'} | ${v.caps || '–'} | ${v.n} |\n`;
}

// 3. All records
md += `\n## 3. All records\n\n| Jurisdiction | Funder · instrument | Year/period | Original | EUR | Type | OSS share | Ev. | Source |\n|---|---|---|---|---|---|---|---|---|\n`;
for (const r of rows.sort((a, b) => a.side.localeCompare(b.side) || order.indexOf(a.level) - order.indexOf(b.level) || String(a.jurisdiction).localeCompare(b.jurisdiction) || a.year - b.year)) {
  const src = (r.sources || [])[0];
  md += `| ${r.jurisdiction}${r.province ? ` (${r.province})` : ''} | ${r.funder} · ${r.instrument} | ${r.period || r.year} | ${fmtOrig(r)} | ${fmt(r.eur)}${r.approxRate ? '*' : ''} | ${r.amount_type}${r.summable ? ' ✓' : ''} | ${r.oss_share} | ${r.evidence} | ${src ? `[link](${src})` : '–'} |\n`;
}
md += `\n✓ = counted in totals. * = latest available ECB rate used.\n`;

// 4. Coverage
if (coverage.length) {
  md += `\n## 4. Coverage: jurisdictions searched\n\n| Side | Jurisdiction | Result | Note |\n|---|---|---|---|\n`;
  for (const c of coverage.sort((a, b) => String(a.side || '').localeCompare(String(b.side || '')) || String(a.jurisdiction).localeCompare(b.jurisdiction))) {
    md += `| ${c.side || ''} | ${c.jurisdiction} | ${c.result} | ${(c.note || '').replace(/\|/g, '/')} |\n`;
  }
}
md += `\n---\n${NOTICE}\n`;

fs.writeFileSync(path.join(root, 'docs/FUNDING-COMPARISON.md'), md);
fs.mkdirSync(path.join(root, 'site/data'), { recursive: true });
fs.writeFileSync(path.join(root, 'site/data/funding.json'), JSON.stringify({
  generated: new Date().toISOString(),
  notice: { en: 'Open-source research from public sources; incomplete and correctable. Contribute via GitHub issues or email.', issues: ISSUES, email: EMAIL },
  fx, records: rows,
}, null, 2) + '\n');
console.log(`records ${rows.length}, summable ${rows.filter((r) => r.summable).length}`);
